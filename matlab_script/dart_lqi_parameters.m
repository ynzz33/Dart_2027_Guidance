% ========================================================================
% 飞镖 LQI 力矩控制器 + Pitch 保护型零空间分配 — 参数配置文件
% ========================================================================
% 本文件只包含参数定义，不执行任何计算。
% 由主脚本 dart_attitude_lqi_torque_pitch_protected.m 调用。
%
% 所有占位符（待 SolidWorks / CFD / 台架标定的参数）均用
% "PLACEHOLDER" 标注，方便后续搜索替换。
%
% 坐标系约定（机体系 ENU）：
%   X = 右（roll 轴）
%   Y = 前（pitch 轴）
%   Z = 上（yaw 轴）
%
% 状态定义：
%   xa = [e_roll, e_pitch, e_yaw, p, q, r, ∫e_roll, ∫e_pitch, ∫e_yaw]'
%   e_* : 姿态角误差，rad（测量 − 目标）
%   p,q,r : 机体角速度，rad/s
%   ∫e_* : 姿态角误差积分，rad·s
%
% 控制量定义：
%   tau = [Mx, My, Mz]'  % 三轴力矩，N·m
%
% 舵面顺序（全线统一）：
%   [UL, UR, DR, DL] = [左上, 右上, 右下, 左下]
% ========================================================================

% ======================== 物理常量 ========================
g_ac = 9.81;            % 重力加速度，m/s²
rho_ac = 1.225;          % 海平面空气密度，kg/m³

% ======================== 转动惯量（SolidWorks） ========================
% 单位：kg·m²
% 来源：SolidWorks 截图，已换算 g·mm² → kg·m²（×1e-9）
Ixx_ac = 307131.230e-9;    % 绕 roll 轴（机体 X = 右）
Iyy_ac = 1580238.787e-9;   % 绕 pitch 轴（机体 Y = 前）
Izz_ac = 1589776.981e-9;   % 绕 yaw 轴（机体 Z = 上）

% PLACEHOLDER: 交叉惯量暂设 0，待 SolidWorks 数据
Ixy_ac = 15335.950e-9;     % = -Lxy （交叉惯量积）
Ixz_ac = 2976.203e-9;      % = -Lxz
Iyz_ac = -4624.159e-9;     % = -Lyz （注意负号！）

% 完整惯量矩阵（3×3，对称正定）
I_body = [ Ixx_ac, -Ixy_ac, -Ixz_ac;
          -Ixy_ac,  Iyy_ac, -Iyz_ac;
          -Ixz_ac, -Iyz_ac,  Izz_ac ];

I_inv = inv(I_body);    % 惯量逆矩阵，用于状态空间模型

% ======================== PLACEHOLDER: 舵面位置 ========================
% 每片舵面气动中心相对质心的位置向量，单位 m，机体系坐标
% 列序：[UL, UR, DR, DL]
% 来源：SolidWorks（待机械提供精确值）
%
% 当前占位值：基于 X 翼 45° 几何假设
%   - 机翼在 XZ 平面内，与竖直方向成 45°（从尾向头看）
%   - r_ac: 翼面气动中心横向距离（X 分量），≈ 半翼展在 X 向投影
%   - a_ac: 翼面气动中心距质心纵向距离（Y 分量）
%   - Z 分量 = ±r_ac（X 翼 45° → |Z| = |X|；上翼面 +Z，下翼面 -Z）
%
%   UL(左上): X=-r_ac, Y=+a_ac, Z=+r_ac  (左、前、上)
%   UR(右上): X=+r_ac, Y=+a_ac, Z=+r_ac  (右、前、上)
%   DR(右下): X=+r_ac, Y=-a_ac, Z=-r_ac  (右、后、下)
%   DL(左下): X=-r_ac, Y=-a_ac, Z=-r_ac  (左、后、下)
%
% ⚠ 以下为几何推导占位值，非 SolidWorks 实测。台架前必须替换！
r_ac  = 0.057;   % roll 力臂，m（斜翼展160mm→半翼展X投影=80×cos45°≈57mm）
a_ac  = 0.080;   % pitch/yaw 力臂占位，m（舵面到质心纵向距离 ≈ 80mm）

r_UL = [-r_ac;  a_ac;  r_ac];   % 左上：X-、Y+、Z+（上翼面）
r_UR = [ r_ac;  a_ac;  r_ac];   % 右上：X+、Y+、Z+（上翼面）
r_DR = [ r_ac; -a_ac; -r_ac];   % 右下：X+、Y-、Z-（下翼面）
r_DL = [-r_ac; -a_ac; -r_ac];   % 左下：X-、Y-、Z-（下翼面）

r_surface = [r_UL, r_UR, r_DR, r_DL];   % 3×4 矩阵

% ======================== PLACEHOLDER: 舵面气动力方向 ========================
% 每片舵面正偏转（δ > 0）时气动力的单位方向向量（机体系）
% 列序：[UL, UR, DR, DL]
%
% 推导：X 翼 45° 布局，舵面初始与来流平行（攻角 = 0）
% 舵面法向量 = flow × span（flow = [0,1,0] 沿 Y 轴正向）
% span 方向取决于舵面方位角 θ（从 +Z 顺时针，从尾向头看）：
% span 方向取决于舵面方位角 θ（从 +Z 顺时针，从尾向头看）：
%   UL: θ=135°, span=[cos135°,0,sin135°]=[-0.707,0,0.707]
%   UR: θ=45°,  span=[cos45°,0,sin45°]=[0.707,0,0.707]
%   DR: θ=315°, span=[cos315°,0,sin315°]=[0.707,0,-0.707]
%   DL: θ=225°, span=[cos225°,0,sin225°]=[-0.707,0,-0.707]
%
% 法向量 = [0,1,0] × span = [cosθ, 0, -sinθ]
%
%   UL: n = [cos135°, 0, -sin135°] = [-0.707, 0, -0.707]
%   UR: n = [cos45°,  0, -sin45°]  = [ 0.707, 0, -0.707]
%   DR: n = [cos315°, 0, -sin315°] = [ 0.707, 0,  0.707]
%   DL: n = [cos225°, 0, -sin225°] = [-0.707, 0,  0.707]
%
% ⚠ 警告：以上方向向量是纯几何推导，台架前必须逐片核验符号！
%         若某片方向反了（仿真发散/台架打反），翻对应 n 向量的符号。
%         符号错误 = 正反馈，调 Q/R 救不回来。

n_UL = [-0.70710678; 0; -0.70710678];   % 力朝左下
n_UR = [ 0.70710678; 0; -0.70710678];   % 力朝右下
n_DR = [ 0.70710678; 0;  0.70710678];   % 力朝右上
n_DL = [-0.70710678; 0;  0.70710678];   % 力朝左上

n_surface = [n_UL, n_UR, n_DR, n_DL];   % 3×4，单位向量

% ======================== PLACEHOLDER: 舵面气动参数 ========================
S_surface = 15e-6;      % 单片可控舵面面积 15 mm²（四片相同）
S_wing_total = 55e-6;   % 整翼总面积 55 mm²（参考，不直接参与 H_tau）
C_F_delta = 5.0;        % 舵效系数，1/rad（≈ 薄翼 CLα，占位符，待 CFD/风洞/辨识）
                         % C_Fδ ≠ CLα，物理含义不同，此处仅占位

% ======================== 舵面限位 ========================
delta_max_deg = 60;                % 舵偏限幅，°
delta_max_rad = deg2rad(delta_max_deg);

% ======================== 采样周期 ========================
Ts = 0.001;             % 1 kHz 控制周期，s

% ======================== 速度调度 ========================
V_schedule = 1.0:0.1:20.0;         % 调度速度表，m/s
V_ref = 6.0;                         % 标称/设计速度，m/s（嵌入式当前使用此值）
K_poly_order = 5;                    % K_lqi(V) 多项式拟合阶数

% ======================== [扩展点1] 气动阻尼/恢复 ========================
% 启用后 A(V) 含气动项，K_lqi(V) 随速变化，需恢复速度表架构（见 lqi_torque.c 注释）
DART_LQI_ENABLE_AERO_A = false;

% 以下系数定义在 V_ref 处。启用后自动按 V 缩放：阻尼∝V, 恢复∝V²
% 来源：CFD 吹风 / 飞行辨识 / 台架扫频
Dp_ref   = 0;   % roll damping, 1/s          PLACEHOLDER  (应为负)
Dq_ref   = 0;   % pitch damping, 1/s         PLACEHOLDER  (应为负)
Dr_ref   = 0;   % yaw damping, 1/s           PLACEHOLDER  (应为负)
Cm_pitch_ref = 0;   % pitch restoring, 1/s²  PLACEHOLDER  (应为负)
Cm_yaw_ref   = 0;   % yaw restoring, 1/s²    PLACEHOLDER  (应为负)

% ======================== [扩展点2] 舵面气动参数 ========================
% 以下占位符影响 H_tau(V) = 0.5·ρ·V²·S·C_Fδ · cross(r,n)
% 来源：SolidWorks(面积/位置) + CFD(舵效)
% S_surface, C_F_delta, r_surface, n_surface 已在前面定义

% ======================== [扩展点3] 非线性/耦合项 ========================
% 占位：攻角相关气动、陀螺耦合、重心偏移、舵面铰链力矩
% 后续在此区域新增参数

% ======================== LQI 权重 ========================
% Q_aug: 9×9 状态权重（角度误差 + 角速度 + 积分误差）
% 状态顺序：[e_roll, e_pitch, e_yaw, p, q, r, ∫e_roll, ∫e_pitch, ∫e_yaw]
Q_aug = diag([ ... 
    20.0,   ...  % e_roll  角度误差权重（高：roll 要追准）
    0.05,   ...  % e_pitch 角度误差权重（极低：不主动追 pi tch 角度）
    100,    ...  % e_yaw   角度误差权重（高：yaw 要追准）
    1.0,    ...  % p (roll rate)  权重
    0.2,    ...  % q (pitch rate) 权重（低：只做弱阻尼）
    1.0,    ...  % r (yaw rate)   权重
    0.0001, ...  % ∫e_roll  积分权重（阶段 1 = 0，稳定后再加）
    0.0001, ...  % ∫e_pitch 积分权重（= 0：pitch 不做积分追踪，仅阻尼）
    30.0     ...  % ∫e_yaw   积分权重（阶段 1 = 0，稳定后再加）
]);

% R_tau: 3×3 三轴力矩惩罚
% 顺序：[Mx, My, Mz] = [roll 力矩, pitch 力矩, yaw 力矩]
% R 越大 → 对应轴力矩越保守 → 舵面动作越小
R_tau = diag([ ...
    10.0,  ...  % roll  力矩惩罚
    10.0,  ...  % pitch 力矩惩罚（与 roll/yaw 同值起步，靠 Q 的 pitch 低权重做区分）
    10.0   ...  % yaw   力矩惩罚
]);

% ======================== 零空间分配器权重 ========================
% 优化目标：J = λ_pitch·(h_pitch·δ)² + λ_servo·(δ'·δ)
% λ_pitch 越大 → 越优先压低 Pitch 力矩
% λ_servo 越大 → 越优先减少总舵面动作
lambda_pitch = 1.0;    % Pitch 力矩最小化权重
lambda_servo = 1.0;      % 舵面动作最小化权重

% ======================== 积分分离阈值 ========================
% 姿态误差 ≥ 阈值 → 清零并冻结积分（P/D 主导拉回）
% 姿态误差 <  阈值 → 开启积分（消静差）
integ_threshold_deg = 0.5;          % °
integ_threshold_rad = deg2rad(integ_threshold_deg);

% ======================== 仿真参数 ========================
T_sim = 2.0;             % 仿真时长，s
V_sim = 6.0;             % 仿真飞行速度（m/s），改此值测试不同速度下舵效
% 初始姿态扰动（用于验证闭环收敛）
x0_attitude_deg = [15;   % roll 初始误差，°
                   10;   % pitch 初始误差，°
                   10];  % yaw 初始误差，°
x0_rates_deg_s  = [0;    % p 初始角速度，°/s
                    0;    % q
                    0];   % r

% ======================== 打印参数摘要 ========================
fprintf('========== 飞镖 LQI 参数加载完成 ==========\n');
fprintf('I_body (kg·m²): Ixx=%.4e, Iyy=%.4e, Izz=%.4e\n', Ixx_ac, Iyy_ac, Izz_ac);
fprintf('V_ref = %.1f m/s, Ts = %.0f Hz, 舵面限幅 = ±%.0f°\n', V_ref, 1/Ts, delta_max_deg);
fprintf('调度: %.1f ~ %.1f m/s, %d 阶多项式\n', V_schedule(1), V_schedule(end), K_poly_order);
fprintf('Q_int = [%.0e, %.0e, %.0e], R_tau = [%.1f, %.1f, %.1f]\n', ...
    Q_aug(7,7), Q_aug(8,8), Q_aug(9,9), diag(R_tau));
fprintf('λ_pitch=%.0f, λ_servo=%.0f, integ_threshold=%.1f°\n', ...
    lambda_pitch, lambda_servo, integ_threshold_deg);
fprintf('=============================================\n');

% 直接运行本文件时自动链式运行主脚本（被主脚本 run() 调用时跳过）
if isscalar(dbstack)
    fprintf('>>> 自动运行主脚本...\n');
    run('dart_attitude_lqi_torque_pitch_protected');
end
