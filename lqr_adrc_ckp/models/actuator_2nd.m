function [pos, st] = actuator_2nd(cmd, st, params)
% =========================================================================
% ACTUATOR_2ND  二阶「舵机模型」+ 速率/位置限幅（4 个舵面一起向量化处理）
% -------------------------------------------------------------------------
% 【为什么舵机要建模，不能瞬间到位】真实舵机有惯性、有最大转速、有最大行程。
%   控制器算出“想要打 20°”，舵机不可能瞬间跳过去——它像一个有阻尼的弹簧一样
%   “追”过去，而且每秒最多转 200°、最多打到 ±25°。把这些限制建进来，仿真才真实，
%   也才能暴露“指令太猛 → 舵机跟不上 → 饱和”这类工程问题。
%
% 【二阶动力学（一个典型的“质量-弹簧-阻尼”系统）】
%       δ̈ = ωn²·(δ_cmd − δ) − 2ζ·ωn·δ̇
%   - ωn（自然频率，本项目 2π·15 ≈ 94 rad/s）：决定舵机多快，≈15Hz 带宽；
%   - ζ（阻尼比 0.7）：决定追过去时会不会超调震荡，0.7 是“快而几乎不超调”的经典值。
%
% 【两道硬限制，顺序很重要：先限速率，再限位置】
%   - 速率限 |δ̇| ≤ 200°/s：舵机每秒最多转这么多；
%   - 位置限 |δ| ≤ 25°：舵面最大行程；
%   触到位置限时，把“还想往限外冲”的那个方向的速度清零，避免数值上“撞墙后继续积分”。
%
% 【离散化】前向欧拉，步长 Ts=1e-3：先用加速度更新速度，再用速度更新位置。
%
% 【入参】
%   cmd    - 4×1 舵偏指令 (rad)，来自 control_alloc
%   st     - 状态结构体 {pos,vel}（当前位置/速度）；首次调用传 [] 自动初始化为 0
%   params - 参数（servo.wn / zeta / pos_max / rate_max, sim.Ts）
% 【返回】
%   pos    - 4×1 实际舵偏 (rad)，送往气动/动力学
%   st     - 更新后的状态（pos/vel）
% =========================================================================

    wn = params.servo.wn;  zeta = params.servo.zeta;  Ts = params.sim.Ts;

    % ---- 首次调用：舵面从 0°、0 速度起步 ----
    if isempty(st)
        st.pos = zeros(4,1);  st.vel = zeros(4,1);
    end
    cmd = cmd(:);

    % ---- 二阶动力学：先算加速度，再积分出速度 ----
    acc = wn^2*(cmd - st.pos) - 2*zeta*wn*st.vel;
    vel = st.vel + Ts*acc;

    % ---- 速率限：速度先被夹在 ±rate_max 内 ----
    vel = max(min(vel, params.servo.rate_max), -params.servo.rate_max);

    % ---- 用（限速后的）速度积分出新位置 ----
    pos = st.pos + Ts*vel;

    % ---- 位置限 ±pos_max；触限则清掉“继续往限外”的速度（抗撞限积分）----
    hi = pos >  params.servo.pos_max;
    lo = pos < -params.servo.pos_max;
    pos = max(min(pos, params.servo.pos_max), -params.servo.pos_max);
    vel(hi & vel > 0) = 0;          % 已到正限还想正向加速 → 清零
    vel(lo & vel < 0) = 0;          % 已到负限还想负向加速 → 清零

    % ---- 存状态供下一步 ----
    st.pos = pos;  st.vel = vel;
end
