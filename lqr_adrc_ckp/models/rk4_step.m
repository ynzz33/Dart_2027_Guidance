function x_next = rk4_step(x, delta, wind_ned, params, Ts)
% =========================================================================
% RK4_STEP  四阶龙格-库塔（RK4）定步长积分一步 —— 让飞镖“往前飞 Ts 秒”
% -------------------------------------------------------------------------
% 【这个函数干什么】我们有“状态变化率”dx=dart_6dof(x,…)，要由当前状态 x 算出
%   Ts 秒之后的状态 x_next。最简单的办法是欧拉法 x_next=x+Ts·dx，但它精度低、易发散。
%   RK4 在一步之内“试探”了 4 次斜率（起点、两次中点、终点），再加权平均，
%   精度高得多（误差 ∝ Ts⁵），是工程仿真最常用的定步长积分器。
%
% 【四次斜率】
%   k1 = f(起点)            —— 用当前状态算一次斜率
%   k2 = f(用 k1 走半步)    —— 中点斜率（第一次估计）
%   k3 = f(用 k2 走半步)    —— 中点斜率（修正一次）
%   k4 = f(用 k3 走整步)    —— 终点斜率
%   x_next = x + (Ts/6)·(k1 + 2·k2 + 2·k3 + k4)   ← 中点权重更高
%
% 【零阶保持 ZOH】这一步内，控制量 delta 和风 wind_ned 都保持不变。
%   这符合数字控制的真实情况：控制器每个采样周期算一次舵令，期间舵令不变。
%
% 【入参】x(12) 当前状态；delta(4) 舵偏；wind_ned(3) 风；params 参数；Ts 步长(s)
% 【返回】x_next(12) 下一时刻状态
% =========================================================================
    k1 = dart_6dof(x,             delta, wind_ned, params);
    k2 = dart_6dof(x + 0.5*Ts*k1, delta, wind_ned, params);
    k3 = dart_6dof(x + 0.5*Ts*k2, delta, wind_ned, params);
    k4 = dart_6dof(x +     Ts*k3, delta, wind_ned, params);
    x_next = x + (Ts/6)*(k1 + 2*k2 + 2*k3 + k4);
end
