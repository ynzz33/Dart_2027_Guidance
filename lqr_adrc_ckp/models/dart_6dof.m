function dx = dart_6dof(x, delta, wind_ned, params)
% =========================================================================
% DART_6DOF  无动力飞镖「6 自由度（6DOF）非线性运动方程」—— 整个仿真的“物理引擎”
% -------------------------------------------------------------------------
% 【这个函数干什么】给定飞镖此刻的状态 x、舵面偏角 delta、当前风 wind_ned，
%   算出状态的“变化率” dx（即 dx/dt）。外面的积分器 rk4_step 拿着 dx 往前走一小步，
%   就得到下一时刻的状态。反复调用 → 飞镖就“飞”起来了。
%
% 【什么是 6 自由度】一个刚体在空间里完整地动，需要 6 个自由度：
%     3 个平动（前后/左右/上下）+ 3 个转动（滚转/俯仰/偏航）。
%   我们用 12 个状态量来完整描述它（每个自由度的“位置”和“速度”各一个）：
%
%     x = [ pN  pE  pD ;   % ① 位置：在大地系(NED)的 北/东/地 坐标 (m)   —— 平动的“位置”
%           u   v   w  ;   % ② 速度：在机体系的 前/右/下 速度分量 (m/s) —— 平动的“速度”
%           φ   θ   ψ  ;   % ③ 姿态：滚转/俯仰/偏航 欧拉角 (rad)        —— 转动的“位置”
%           p   q   r  ];  % ④ 角速度：绕机体 X/Y/Z 轴的转速 (rad/s)    —— 转动的“速度”
%
%   坐标系约定：
%     - NED 大地系：N=正北, E=正东, D=指向地心（向下为正）。所以高度 = -pD。
%     - 机体系：X=机头朝前, Y=右翼, Z=机腹朝下（右手系）。
%
% 【三组方程，分别管平动、转动、姿态运动学】
%   (A) 平动（牛顿第二定律，在“随飞镖一起转”的机体系里写，要补 -ω×V 项）：
%         V̇_body = (F_气动 + F_重力)/m  −  ω × V
%       那个 −ω×V 叫“科里奥利/向心项”：因为机体系本身在转，所以即使合力为零，
%       速度矢量在机体系里的分量也会变化，必须扣掉这一项才正确。
%   (B) 转动（欧拉转动方程）：
%         ω̇ = I⁻¹ · ( M_气动 − ω × (I·ω) )
%       那个 −ω×(Iω) 叫“陀螺/惯性耦合项”：高速旋转的刚体三个轴会互相“拽”。
%   (C) 姿态运动学：机体角速度 [p;q;r] 不等于欧拉角变化率 [φ̇;θ̇;ψ̇]，
%       需要一个随姿态变化的矩阵 H 来换算：[φ̇;θ̇;ψ̇] = H(φ,θ)·[p;q;r]。
%
% 【入参】
%   x        - 12×1 状态（见上）
%   delta    - 4×1 物理舵偏 (rad)，传给气动函数算控制力矩
%   wind_ned - 3×1 NED 风速 (m/s)，气动函数用它算相对气流
%   params   - 参数结构体（质量 m、惯量 I、重力 g 等）
% 【返回】
%   dx       - 12×1 状态导数（与 x 同顺序），交给 rk4_step 积分
% =========================================================================

    % ---- 从 12 维状态里把各部分拆出来，命名清楚便于阅读 ----
    uvw = x(4:6);                       % 机体系速度 [u;v;w]
    phi = x(7); theta = x(8); psi = x(9);   % 姿态欧拉角
    pqr = x(10:12);                     % 机体角速度 [p;q;r]

    m = params.body.m;                  % 质量 (kg)
    I = params.body.I;                  % 3×3 转动惯量矩阵 (kg·m²)

    % ---- (1) 气动力 / 力矩（机体系）：由 dart_aero 按动压、攻角、舵偏算出 ----
    [F_aero, M_aero] = dart_aero(x, delta, wind_ned, params);

    % ---- (2) 重力：在 NED 里是 [0;0;g]（指向地心），转到机体系才能和气动力相加 ----
    R_n2b  = dcm_ned2body(phi, theta, psi);     % NED → 机体 的旋转矩阵
    F_grav = m * (R_n2b * [0; 0; params.env.g]);

    % ---- (A) 平动方程：V̇ = 合力/m − ω×V（机体系，含科里奥利项）----
    dV = (F_aero + F_grav)/m - cross(pqr, uvw);

    % ---- (B) 转动方程：ω̇ = I⁻¹(M − ω×(Iω))（含陀螺耦合项）----
    dpqr = I \ (M_aero - cross(pqr, I*pqr));     % “I \ y” 即 inv(I)*y，但更快更稳

    % ---- (C) 姿态运动学：[φ̇;θ̇;ψ̇] = H(φ,θ)·[p;q;r] ----
    % 当俯仰 θ=±90° 时公式里会出现 1/cos(θ)=∞（万向锁奇异），这里给 cos(θ) 设个下限避免除零。
    cth = cos(theta); cth = sign(cth + (cth==0))*max(abs(cth), 1e-4);
    tth = sin(theta)/cth;               % tan(θ)，用限幅后的 cth 防爆
    sphi = sin(phi); cphi = cos(phi);
    H = [1, sphi*tth,  cphi*tth;        % 欧拉角速率转换矩阵（ZYX 顺序）
         0, cphi,     -sphi;
         0, sphi/cth,  cphi/cth];
    dEuler = H * pqr;

    % ---- 位置导数：把机体系速度转回 NED，就是位置在大地系的变化率 ----
    dPos = R_n2b' * uvw;                % R_n2b' = 机体→NED（正交矩阵转置=逆）

    % ---- 按状态顺序拼成 12×1 导数返回 ----
    dx = [dPos; dV; dEuler; dpqr];
end
