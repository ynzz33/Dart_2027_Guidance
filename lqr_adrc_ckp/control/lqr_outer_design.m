function K = lqr_outer_design(params, Q, R)
% =========================================================================
% LQR_OUTER_DESIGN  外环「姿态 LQR」增益设计 —— 把“姿态角误差”变成“期望角速度”
% -------------------------------------------------------------------------
% 【外环干什么】它是控制的“大脑上层”：看当前姿态角离目标差多少，
%   决定“应该以多快的角速度转过去”，把这个期望角速度 [p_c;q_c;r_c] 交给内环 LADRC 执行。
%
% 【被控对象极简：一个积分器】对“姿态角”这一层，物理关系就是
%       姿态角的变化率 = 角速度，即 [φ̇;θ̇;ψ̇] = [p;q;r]
%   写成状态空间就是 A=0₃, B=I₃（三个解耦的纯积分器）。我们把角速度当“油门”来调姿态角。
%
% 【LQR 是什么】线性二次型调节器：自动选一个“最划算”的反馈增益 K，
%   让代价 J=∫(xᵀQx + uᵀRu)dt 最小。直观理解：
%     - Q 大 → 更在乎“姿态误差快点消掉” → 响应快、增益大；
%     - R 大 → 更在乎“别用太猛的角速度指令” → 响应柔和、增益小。
%   本项目 Q=diag([36 36 3.6]), R=diag([1 1 0.1]) → 解出 K≈diag([6 6 6])。
%
% 【对“解耦积分器”有解析解（便于理解 K 怎么来的）】
%       K = diag( sqrt(diag(Q)./diag(R)) )
%   每个通道闭环变成 ẋ = −K_ii·x，是一阶衰减：
%       时间常数 τ = 1/K_ii，  2% 调节时间 ts ≈ 3.91·τ。
%   K=6 → τ≈0.167s → 外环 ts≈0.65s；与内环 wc=16 串联后整体更快（详见 README 整定指南）。
%
% 【用法】
%   K = lqr_outer_design(params)        % 用 params.lqr.Q / params.lqr.R（默认）
%   K = lqr_outer_design(params, Q, R)  % 临时指定权重，做整定对比时用
% 【返回】K(3×3) 增益矩阵；运行时 [p_c;q_c;r_c] = K·(att_ref − att) + 参考微分前馈
% =========================================================================

    % ---- 缺省参数：没传 Q/R 就用 params 里整定好的值 ----
    if nargin < 2 || isempty(Q); Q = params.lqr.Q; end
    if nargin < 3 || isempty(R); R = params.lqr.R; end

    % ---- 积分器模型 A=0, B=I，调 MATLAB 的 lqr 解黎卡提方程得增益 ----
    A = zeros(3);
    B = eye(3);
    K = lqr(A, B, Q, R);
end
