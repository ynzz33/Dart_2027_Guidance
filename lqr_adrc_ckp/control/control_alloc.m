function [delta, info] = control_alloc(tau_c, qbar, params)
% =========================================================================
% CONTROL_ALLOC  X 构型「控制分配」—— 把 3 个期望力矩，分摊给 4 个舵面
% -------------------------------------------------------------------------
% 【为什么需要分配】内环 LADRC 给出的是“我想要多大的滚转/俯仰/偏航力矩”（3 个数），
%   但飞镖有 4 个舵面，每个舵面同时对这 3 个力矩都有贡献（X 构型，舵轴与机体成 45°）。
%   控制分配就是解一个“反问题”：已知想要的 3 个力矩，求 4 个舵面各打多少度。
%   4 个未知数、3 个方程 → 解不唯一（有冗余）→ 用“加权最小二乘”挑一个最优解。
%
% 【舵效模型（与 dart_aero 完全一致，保证分配算的和实际产生的对得上）】
%       tau = B · delta，   B = diag(g) · E
%   - g = q̄·S·d·[Clδa; Cmδe; Cnδr]：单位舵偏在三个轴上产生的力矩（**随动压 q̄ 变化**）
%   - E (3×4)：X 构型几何效率矩阵（滚转/俯仰行含 cos45°，偏航行是 ±1 差动）
%
% 【动压调度（本设计应对“速度大幅衰减”的关键）】
%   B 里含 q̄。速度高→q̄ 大→同样力矩只需小舵偏；速度低→q̄ 小→自动解出更大舵偏来补偿。
%   因此只要舵不饱和，闭环性能几乎不随速度变化——这正是“60→20 m/s 性能降级<30%”的来源。
%
% 【加权最小二乘 + 偏航低权重（应对“偏航效率极低”）】
%   求解：  min ‖W·(B·delta − tau)‖² + ε‖delta‖²
%      ⇒   delta = (Bᵀ W² B + εI)⁻¹ Bᵀ W² · tau_c
%   - W=diag([1,1,0.05])：偏航权重故意取很低。因为偏航舵效 Cndr 极小，硬要用舵面控偏航
%     会需要十几度大舵偏、吃光 4 个舵的舵权、把滚转/俯仰也拖垮。低权重=“放弃主动控偏航”，
%     交给气动 Cnβ/Cnr 被动增稳（风向标效应），把宝贵舵权留给强轴。
%   - ε·I：很小的正则项，防止 BᵀW²B 接近奇异时求逆数值爆掉（吉洪诺夫正则）。
%   （这是用户提纲 δ=pinv(W·diag(K_inv)·E)·W·tau 的等价、数值更稳健的写法。）
%
% 【入参】
%   tau_c  - 3×1 期望力矩 [L_c;M_c;N_c] (N·m)，来自内环 LADRC
%   qbar   - 标量动压 (Pa)，用于构造 B（动压调度）
%   params - 参数（几何 S/d、舵效系数、E、W、eps、舵机位置限）
% 【返回】
%   delta  - 4×1 物理舵偏指令 (rad)，已做 ±pos_max 位置饱和
%   info   - 诊断: info.B(3×4 效率矩阵)，info.sat(本步是否触饱和，逻辑量)
% =========================================================================

    S = params.body.S;  d = params.body.d;

    % ---- 构造随动压变化的舵效矩阵 B = diag(g)·E ----
    g = qbar * S * d * [params.aero.Clda; params.aero.Cmde; params.aero.Cndr];
    B = diag(g) * params.alloc.E;          % 3×4 力矩效率矩阵

    % ---- 加权 + 正则 ----
    W  = params.alloc.W;                   % 3×3 对角加权（偏航=0.05，很低）
    W2 = W.^2;                             % 最小二乘里用的是 W²
    epsI = params.alloc.eps * eye(4);      % 4×4 正则项 εI

    % ---- 加权最小二乘闭式解（即加权伪逆）----
    delta = (B'*W2*B + epsI) \ (B'*W2*tau_c);

    % ---- 位置饱和 ±25°（速率限制在舵机环节 actuator_2nd 里做）----
    pm  = params.servo.pos_max;
    sat = any(abs(delta) > pm);            % 只要有任一舵超限就记一次饱和
    delta = max(min(delta, pm), -pm);

    if nargout > 1
        info.B = B;  info.sat = sat;
    end
end
