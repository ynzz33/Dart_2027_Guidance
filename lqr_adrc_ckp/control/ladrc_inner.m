function [u, st] = ladrc_inner(omega_cmd, omega_meas, st, params, u_act)
% =========================================================================
% LADRC_INNER  内环「线性自抗扰控制」(Linear Active Disturbance Rejection Control)
%              —— 把“期望角速度”变成“期望力矩”，并实时估计、对消一切扰动
% -------------------------------------------------------------------------
% 【一句话原理】LADRC 不需要精确知道飞镖的模型。它把“所有我没建模的东西”
%   （气动耦合、风扰、参数误差、非线性…）统统打包成一个看不见的“总扰动 f”，
%   用一个叫 LESO 的观测器把 f 实时估出来，然后在控制量里把它直接减掉。
%   于是复杂的非线性对象被“拉直”成一个简单的积分器，再用最简单的比例控制就能管好。
%
% 【被控对象怎么看】每个通道（滚转 p / 俯仰 q / 偏航 r）都近似成一阶系统：
%       ω̇ = f + b0·u
%   其中 u=力矩，b0=1/转动惯量（力矩→角加速度的增益），f=上面说的“总扰动”。
%
% 【LESO：扩张状态观测器（这里用二阶，估 2 个量）】
%       z1 → 跟踪角速度 ω        （估计的“状态”）
%       z2 → 跟踪总扰动 f        （“扩张”出来的额外状态，这是 ADRC 的精髓）
%   更新律（前向欧拉离散，e=实测−估计）：
%       e  = ω_meas − z1
%       z1 ← z1 + Ts·( z2 + β1·e + b0·u )
%       z2 ← z2 + Ts·( β2·e )
%   观测器增益按“带宽配置法”取：β1 = 2·ω0，β2 = ω0²（ω0=观测器带宽，越大越快但越怕噪声）。
%
% 【控制律：先对消扰动，再做比例控制】
%       u = ( ωc·(ω_cmd − z1) − z2 ) / b0
%   读法：括号里 ωc·(误差) 是普通比例控制（ωc=控制带宽，决定响应快慢）；
%         「− z2」就是把估出来的总扰动直接顶掉；最后「/b0」把“想要的角加速度”换算成力矩。
%
% 【抗饱和 anti-windup（很重要的工程细节）】
%   舵机会饱和（±25°），导致“实际产生的力矩” ≠ “LADRC 想要的力矩 u”。
%   若 LESO 仍按“想要的 u”更新，它会误以为对象没响应而把 z2 越积越大 → 发散。
%   修正：把“实际执行力矩 u_act”（由分配/舵机/饱和反算得到）喂给 LESO 的 b0·u 项，
%   让观测器看到真实输入，饱和时也不发散。u_act 由调用方（主循环）传入。
%
% 【入参】
%   omega_cmd  - 3×1 期望角速度 (rad/s)，来自外环 LQR
%   omega_meas - 3×1 实测角速度 (rad/s)，来自陀螺(含噪声+低通)
%   st         - 状态结构体 {z1,z2,u}；首次调用传 [] 自动初始化
%   params     - 参数（用 adrc.w0=ω0 / adrc.wc=ωc / adrc.b0 / sim.Ts）
%   u_act      - 3×1 上一步“实际执行力矩”（可选）；提供则做抗饱和，缺省退化为用上步指令
% 【返回】
%   u  - 3×1 期望力矩 [L_c;M_c;N_c] (N·m)，送往控制分配
%   st - 更新后的状态（z1/z2/u）
% =========================================================================

    Ts = params.sim.Ts;
    w0 = params.adrc.w0;  wc = params.adrc.wc;      % 观测器带宽 ω0 / 控制带宽 ωc
    b0 = params.adrc.b0(:);                         % 3×1，各通道 1/惯量
    beta1 = 2*w0;  beta2 = w0^2;                    % LESO 带宽配置增益

    omega_cmd  = omega_cmd(:);
    omega_meas = omega_meas(:);

    % ---- 首次调用：初始化观测器状态 ----
    if isempty(st)
        st.z1 = omega_meas;          % z1 初值取当前测量，避免开机瞬间的估计冲击
        st.z2 = zeros(3,1);          % 扰动估计从 0 开始
        st.u  = zeros(3,1);          % 上一步控制量
    end

    % ---- 抗饱和：LESO 优先用“实际执行力矩”，舵机饱和时不发散 ----
    if nargin >= 5 && ~isempty(u_act)
        u_leso = u_act(:);           % 用真实执行的力矩
    else
        u_leso = st.u;               % 没提供就退化为上一步的指令力矩
    end

    % ---- LESO 更新（前向欧拉，用上一步的控制量）----
    e  = omega_meas - st.z1;                         % 观测误差
    z1 = st.z1 + Ts*(st.z2 + beta1.*e + b0.*u_leso); % 跟踪角速度
    z2 = st.z2 + Ts*(beta2.*e);                      % 跟踪总扰动（核心）

    % ---- 线性控制律：比例项 − 扰动对消，再换算成力矩 ----
    u = (wc*(omega_cmd - z1) - z2)./b0;

    % ---- 存状态供下一步 ----
    st.z1 = z1;  st.z2 = z2;  st.u = u;
end
